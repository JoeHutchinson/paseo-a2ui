/** Wraps an A2UI `svgPath` in a self-contained 24x24 SVG document for the host icon renderer. */
export function svgFromPath(path: string): string {
  const safe = path.replace(/[<>"&]/g, "");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="${safe}"/></svg>`;
}
